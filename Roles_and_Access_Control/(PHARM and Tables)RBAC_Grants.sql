-- Pharmacist role and grants
DECLARE
    v_role_count PLS_INTEGER;
BEGIN
    SELECT COUNT(*) INTO v_role_count
    FROM DBA_ROLES
    WHERE role = 'ROLE_PHARMACIST_P2';

    IF v_role_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE ROLE ROLE_PHARMACIST_P2';
    END IF;
END;
/

GRANT ROLE_PHARMACIST_P2 TO USER_PHARMACIST1_P2, USER_PHARMACIST2_P2;
GRANT SELECT ON PROJ_TWO.PATIENT TO ROLE_PHARMACIST_P2;
GRANT SELECT ON PROJ_TWO.PRESCRIPTION TO ROLE_PHARMACIST_P2;
GRANT SELECT ON PROJ_TWO.DISPENSING TO ROLE_PHARMACIST_P2;

-- Procedure EXECUTE grants
GRANT EXECUTE ON PROJ_TWO.CREATE_PRESCRIPTION TO ROLE_DOCTOR_P2;
GRANT EXECUTE ON PROJ_TWO.EDIT_PRESCRIPTION TO ROLE_DOCTOR_P2;
GRANT EXECUTE ON PROJ_TWO.CANCEL_PRESCRIPTION TO ROLE_DOCTOR_P2;
GRANT EXECUTE ON PROJ_TWO.DISPENSE_PRESCRIPTION TO ROLE_PHARMACIST_P2;
GRANT EXECUTE ON PROJ_TWO.UPDATE_DISPENSING_STATUS TO ROLE_PHARMACIST_P2;
GRANT EXECUTE ON PROJ_TWO.CREATE_ADMISSION_BILL TO ROLE_BILLING_P2;
GRANT EXECUTE ON PROJ_TWO.UPDATE_BILL TO ROLE_BILLING_P2;
