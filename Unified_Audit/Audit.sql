--Create Audit Policy
CREATE AUDIT POLICY HOSPITAL_ROLE_AUDIT_P2
    ACTIONS ALL
    ONLY TOPLEVEL;

--Enable Audit Policy for all 7 Roles
AUDIT POLICY HOSPITAL_ROLE_AUDIT_P2
BY USERS WITH GRANTED ROLES
    ROLE_PATIENT_P2,
    ROLE_DOCTOR_P2,
    ROLE_NURSE_P2,
    ROLE_LAB_TECH_P2,
    ROLE_RECEPTIONIST_P2,
    ROLE_BILLING_P2,
    ROLE_PHARMACIST_P2;

--Check Audit Policy against Roles
SELECT
    POLICY_NAME,
    ENABLED_OPTION,
    ENTITY_NAME,
    ENTITY_TYPE,
    SUCCESS,
    FAILURE
FROM AUDIT_UNIFIED_ENABLED_POLICIES
WHERE POLICY_NAME = 'HOSPITAL_ROLE_AUDIT_P2'
ORDER BY ENTITY_NAME;

--View Audit Logs
SELECT EVENT_TIMESTAMP, DBUSERNAME, ACTION_NAME, OBJECT_SCHEMA, OBJECT_NAME,
       CASE WHEN RETURN_CODE = 0 THEN 'SUCCESS' ELSE 'FAILED' END AS RESULT,
       RETURN_CODE, SQL_TEXT, UNIFIED_AUDIT_POLICIES
FROM UNIFIED_AUDIT_TRAIL
WHERE (
    INSTR(UNIFIED_AUDIT_POLICIES, 'HOSPITAL_ROLE_AUDIT_P2') > 0
    OR INSTR(UNIFIED_AUDIT_POLICIES, 'HOSPITAL_OWNER_AUDIT_P2') > 0
)
AND OBJECT_NAME <> 'ALL_IDENTIFIERS'
AND OBJECT_NAME <> 'DUAL'
AND OBJECT_NAME <> 'CLOUD'
AND OBJECT_NAME NOT LIKE '%$%'
AND OBJECT_NAME NOT LIKE 'USER!_%' ESCAPE '!'
AND OBJECT_NAME NOT LIKE 'DBMS!_%' ESCAPE '!'
AND OBJECT_NAME NOT LIKE 'DBA!_%' ESCAPE '!'
AND OBJECT_NAME NOT LIKE 'ALL!_%' ESCAPE '!'
AND OBJECT_NAME NOT LIKE 'NLS!_%' ESCAPE '!'
AND OBJECT_NAME NOT LIKE 'DATABASE!_%' ESCAPE '!'
AND OBJECT_NAME IS NOT NULL
AND UPPER(DBUSERNAME) NOT LIKE '%SYSTEM%'
ORDER BY EVENT_TIMESTAMP DESC;